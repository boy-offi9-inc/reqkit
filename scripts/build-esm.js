#!/usr/bin/env node
// Builds a single, dependency-free ESM bundle of reqkit for browsers, Deno,
// Bun, Cloudflare Workers and anything else that can `import` a file.
//
// No bundler needed: src/ only uses web-standard APIs and relative requires, so
// we wrap each CommonJS module in a function and hand-roll a tiny `require`.
//
//   node scripts/build-esm.js                 → dist/reqkit.mjs and docs/reqkit.mjs
//   node scripts/build-esm.js a.mjs b.mjs     → just those paths

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src");
const pkg = require(path.join(root, "package.json"));

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith(".js")).sort();

let out = `/*! ${pkg.name} v${pkg.version} — ESM bundle (generated by scripts/build-esm.js, do not edit) */\n`;
out += "const __defs = {\n";

for (const file of files) {
  const code = fs.readFileSync(path.join(srcDir, file), "utf8");

  for (const match of code.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)) {
    if (!match[1].startsWith("./")) {
      throw new Error(`${file}: cannot bundle non-relative require("${match[1]}") — the bundle must stay dependency-free`);
    }
  }

  const id = "./" + file.replace(/\.js$/, "");
  out += `${JSON.stringify(id)}: function (module, exports, require) {\n${code}\n},\n`;
}

out += "};\n";
out += [
  "const __cache = {};",
  "function __require(id) {",
  '  const key = id.replace(/\\.js$/, "");',
  "  if (!(key in __defs)) throw new Error(`reqkit bundle: cannot resolve ${id}`);",
  "  if (__cache[key]) return __cache[key].exports;",
  "  const module = (__cache[key] = { exports: {} });",
  "  __defs[key].call(module.exports, module, module.exports, __require);",
  "  return module.exports;",
  "}",
  'const __reqkit = __require("./index");',
  "",
].join("\n");

const names = Object.keys(require(path.join(srcDir, "index.js"))).sort();
out += `export const {\n  ${names.join(",\n  ")},\n} = __reqkit;\n`;
out += "export default __reqkit;\n";

const targets = process.argv.slice(2);
const outputs = targets.length > 0 ? targets : [path.join(root, "dist", "reqkit.mjs"), path.join(root, "docs", "reqkit.mjs")];

for (const target of outputs) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(1)} kB, ${names.length} exports)`);
}
