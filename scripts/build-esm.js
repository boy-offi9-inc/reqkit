#!/usr/bin/env node
// Builds a single, dependency-free ESM bundle of reqkit for browsers, Deno,
// Bun, Cloudflare Workers and anything else that can `import` a file.
//
// No bundler needed: src/ only uses web-standard APIs and relative requires, so
// we wrap each CommonJS module in a function and hand-roll a tiny `require` that
// resolves relative paths (src/ is nested, so "../errors/HTTPError" must work).
//
//   node scripts/build-esm.js                 → dist/reqkit.mjs and playground/reqkit.mjs
//   node scripts/build-esm.js a.mjs b.mjs     → just those paths

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src");
const pkg = require(path.join(root, "package.json"));

// Every .js file under src/ (any depth), keyed by its path relative to src/ without ".js".
function listModules(dir, prefix = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.isDirectory()) out.push(...listModules(path.join(dir, entry.name), `${prefix}${entry.name}/`));
    else if (entry.name.endsWith(".js")) out.push({ id: `${prefix}${entry.name.slice(0, -3)}`, file: path.join(dir, entry.name) });
  }
  return out;
}

const modules = listModules(srcDir);

let out = `/*! ${pkg.name} v${pkg.version} — ESM bundle (generated by scripts/build-esm.js, do not edit) */\n`;
out += "const __defs = {\n";

for (const { id, file } of modules) {
  const code = fs.readFileSync(file, "utf8");

  for (const match of code.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)) {
    if (!match[1].startsWith(".")) {
      throw new Error(`${id}.js: cannot bundle non-relative require("${match[1]}") — the bundle must stay dependency-free`);
    }
  }

  out += `${JSON.stringify(id)}: function (module, exports, require) {\n${code}\n},\n`;
}

out += "};\n";
out += [
  "const __cache = {};",
  "// Resolve a relative request the way node would, against the requiring module's id.",
  "function __resolve(fromId, request) {",
  '  const parts = fromId.split("/").slice(0, -1);',
  '  for (const seg of request.replace(/\\.js$/, "").split("/")) {',
  '    if (seg === "..") parts.pop();',
  '    else if (seg !== "." && seg !== "") parts.push(seg);',
  "  }",
  '  const id = parts.join("/");',
  "  if (id in __defs) return id;",
  '  if (`${id}/index` in __defs) return `${id}/index`;',
  '  if (id === "" && "index" in __defs) return "index";',
  "  throw new Error(`reqkit bundle: cannot resolve ${request} from ${fromId}`);",
  "}",
  "function __load(id) {",
  "  if (__cache[id]) return __cache[id].exports;",
  "  const module = (__cache[id] = { exports: {} });",
  "  __defs[id].call(module.exports, module, module.exports, (request) => __load(__resolve(id, request)));",
  "  return module.exports;",
  "}",
  'const __reqkit = __load("index");',
  "",
].join("\n");

const names = Object.keys(require(path.join(srcDir, "index.js"))).sort();
out += `export const {\n  ${names.join(",\n  ")},\n} = __reqkit;\n`;
out += "export default __reqkit;\n";

const targets = process.argv.slice(2);
const outputs = targets.length > 0 ? targets : [path.join(root, "dist", "reqkit.mjs"), path.join(root, "playground", "reqkit.mjs")];

for (const target of outputs) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(1)} kB, ${names.length} exports)`);
}
